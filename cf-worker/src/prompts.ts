export const FALLBACK_PROMPT = `
Ты — AI-ассистент компании. Отвечай вежливо и профессионально на вопросы клиентов.
Длина ответа: 2–4 предложения. Отвечай только на русском языке.
`.trim();

export function getPrompt(mode: string | undefined, niche: string | undefined): string {
  if (!mode || !niche) return FALLBACK_PROMPT;
  const modePrompts = PROMPTS[mode as Mode];
  if (!modePrompts) return FALLBACK_PROMPT;
  return modePrompts[niche as Niche] ?? FALLBACK_PROMPT;
}
